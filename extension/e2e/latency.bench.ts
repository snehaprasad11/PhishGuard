// Latency benchmark (spec §16): runs N analyses in the real extension and
// records p50/p95. Writes models/latency.json (read by the model card) and
// docs/PERFORMANCE.md. Numbers are measurements from this machine, not claims.
import { readFileSync, writeFileSync } from "node:fs";
import { cpus, platform, release } from "node:os";
import { resolve } from "node:path";
import { browserChannel, expect, finishOnboarding, test } from "./fixtures";

const RUNS = 200;
const root = resolve(import.meta.dirname, "../..");
const fixture: { url: string }[] = JSON.parse(
  readFileSync(resolve(import.meta.dirname, "../tests/fixtures/url-parity.json"), "utf-8"),
);
const metadata = JSON.parse(readFileSync(resolve(root, "models/url-model.json"), "utf-8"));

function percentile(sorted: number[], p: number): number {
  return sorted[Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1)]!;
}
const summarise = (values: number[]) => {
  const sorted = [...values].sort((a, b) => a - b);
  const round = (v: number) => Math.round(v * 100) / 100;
  return { p50: round(percentile(sorted, 50)), p95: round(percentile(sorted, 95)), max: round(sorted.at(-1)!) };
};

test(`latency over ${RUNS} analyses`, async ({ popup, context }) => {
  await finishOnboarding(popup);
  const textarea = popup.getByLabel("Or paste a link or a message");
  const clickToResult: number[] = [];
  const analyse: number[] = [];
  let coldLoadMs = 0;

  for (let i = 0; i < RUNS + 1; i++) {
    // A distinct query string each time, so no run can reuse a previous result.
    await textarea.fill(`${fixture[i % fixture.length]!.url.split("#")[0]}${i % 2 ? "?r=" : "&r="}${i}`);
    const timing = await popup.evaluate(
      () =>
        new Promise<{ elapsed: number; analyseMs: number; loadMs: number }>((done) => {
          // Every run analyses a different address, so the displayed address
          // changing is the signal that this run's verdict is on screen.
          const shown = () => document.querySelector(".address")?.textContent;
          const before = shown();
          const started = performance.now();
          const observer = new MutationObserver(() => {
            const tag = document.querySelector("[data-testid=model-version]");
            if (tag && shown() && shown() !== before) {
              observer.disconnect();
              done({
                elapsed: performance.now() - started,
                analyseMs: Number(tag.getAttribute("data-analyse-ms")),
                loadMs: Number(tag.getAttribute("data-load-ms")),
              });
            }
          });
          observer.observe(document.body, { subtree: true, childList: true, attributes: true });
          [...document.querySelectorAll("button")].find((b) => b.textContent === "Analyse pasted text")!.click();
        }),
    );
    if (i === 0) {
      coldLoadMs = timing.loadMs; // the first analysis also loads the model
      continue;
    }
    clickToResult.push(timing.elapsed);
    analyse.push(timing.analyseMs);
  }

  const result = {
    model_version: metadata.model_version,
    measured_at: new Date().toISOString().slice(0, 10),
    runs: RUNS,
    // From clicking Analyse to the verdict being on screen.
    click_to_result_ms: summarise(clickToResult),
    // Featurise + ONNX inference + evidence, inside the worker.
    analyse_ms: summarise(analyse),
    // Fetching the packaged model and starting ONNX Runtime, once per popup.
    cold_model_load_ms: Math.round(coldLoadMs),
    environment: {
      browser: `${browserChannel} ${context.browser()?.version()}`,
      os: `${platform()} ${release()}`,
      cpu: cpus()[0]?.model.trim(),
    },
  };
  expect(result.click_to_result_ms.p50).toBeGreaterThan(0);

  writeFileSync(resolve(root, "models/latency.json"), JSON.stringify(result, null, 2) + "\n");
  writeFileSync(
    resolve(root, "docs/PERFORMANCE.md"),
    `# Performance

Generated by \`pnpm bench\` in \`extension/\`. These are measurements from one machine, not
guarantees: run the benchmark yourself to get numbers for yours.

| | p50 | p95 | max |
| --- | --- | --- | --- |
| Click Analyse to verdict on screen | ${result.click_to_result_ms.p50} ms | ${result.click_to_result_ms.p95} ms | ${result.click_to_result_ms.max} ms |
| Featurise + inference + evidence (in the worker) | ${result.analyse_ms.p50} ms | ${result.analyse_ms.p95} ms | ${result.analyse_ms.max} ms |

- **Cold model load** (first analysis after opening the popup): ${result.cold_model_load_ms} ms
- **Runs:** ${result.runs} analyses of distinct addresses, after one warm-up
- **Model:** \`${result.model_version}\`
- **Measured:** ${result.measured_at}, ${result.environment.browser}, ${result.environment.os}, ${result.environment.cpu}

The budget in the specification is under 150 ms from click to verdict for the URL model.

## What is being timed

1. The popup posts the address to a Web Worker.
2. The worker turns the address into 33 numbers, runs the ONNX model in ONNX Runtime Web
   (WebAssembly, single thread) and builds the evidence list.
3. The popup renders the verdict.

Nothing in this path touches the network: the model, its metadata and the known-sites list are
packaged inside the extension.
`,
  );
});
